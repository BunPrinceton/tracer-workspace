/* extract-figures.mjs — pull every gallery card EXCEPT the auto-imported
   "Figure" contributions out of gallery/index.html and write them to
   tools/figure-tagger/figures.js (window.FIGURES = [...]) for the Figure Tagger.
   A .js file (not .json) so the tagger works straight from file:// with no server.
   Re-run whenever cards are added to the gallery:
     node work-files/tagger/extract-figures.mjs
*/
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const GALLERY = path.join(ROOT, 'gallery', 'index.html');
const OUT = path.join(ROOT, 'tools', 'figure-tagger', 'figures.js');

const html = fs.readFileSync(GALLERY, 'utf8');
const unesc = s => String(s || '')
  .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
  .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&hellip;/g, '…')
  .replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();

const figures = [];
let skippedNoImage = 0;
const sectionRe = /<section class="dataset-section" id="([^"]+)"[^>]*>([\s\S]*?)<\/section>/g;
let sm;
while ((sm = sectionRe.exec(html))) {
  const [, sectionId, body] = sm;
  const h2 = body.match(/<h2[^>]*>([\s\S]*?)<\/h2>/);
  const gallery = unesc(h2 ? h2[1] : sectionId);
  const figRe = /<figure class="gallery-item" data-category="([^"]+)"([^>]*)>([\s\S]*?)<\/figure>/g;
  let fm;
  while ((fm = figRe.exec(body))) {
    const [, category, attrs, inner] = fm;
    if (category === 'figure') continue;
    const id = (attrs.match(/id="([^"]+)"/) || [])[1];
    if (!id) continue;
    const img = inner.match(/<img src="([^"]+)"[^>]*alt="([^"]*)"/);
    if (!img) { skippedNoImage++; continue; }
    const title = unesc((inner.match(/<h3 class="gallery-title">([\s\S]*?)<\/h3>/) || [])[1]);
    const description = unesc((inner.match(/<p class="gallery-description"[^>]*>([\s\S]*?)<\/p>/) || [])[1]);
    const meta = [...inner.matchAll(/<span class="gallery-meta-item">([\s\S]*?)<\/span>/g)].map(m => unesc(m[1]));
    figures.push({ id, category, sectionId, gallery, src: unesc(img[1]), alt: unesc(img[2]), title, description, meta });
  }
}

const banner = `/* GENERATED by work-files/tagger/extract-figures.mjs on ${new Date().toISOString()} — do not edit by hand.\n   ${figures.length} figures (all gallery cards except data-category="figure"). */\n`;
fs.writeFileSync(OUT, banner + 'window.FIGURES = ' + JSON.stringify(figures, null, 1) + ';\n');
const byGallery = {};
for (const f of figures) byGallery[f.gallery] = (byGallery[f.gallery] || 0) + 1;
console.log(`wrote ${figures.length} figures to ${path.relative(ROOT, OUT)} (skipped ${skippedNoImage} cards without an <img>)`);
for (const [g, n] of Object.entries(byGallery)) console.log(`  ${String(n).padStart(4)}  ${g}`);
